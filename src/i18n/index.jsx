export const translations = { uk, ru, en, es }

// Fix 4 - added Spanish to lang options
export const LANG_OPTIONS = [
  { code: 'uk', label: 'Українська', flag: '🇺🇦' },
  { code: 'ru', label: 'Русский', flag: '🇷🇺' },
  { code: 'en', label: 'English', flag: '🇬🇧' },
  { code: 'es', label: 'Español', flag: '🇪🇸' },
]

export const LangContext = createContext(null)

export function LangProvider({ children }) {
  const [lang, setLang] = useState(() => {
    const saved = localStorage.getItem('fq_lang')
    return saved && translations[saved] ? saved : 'uk'
  })

  const changeLang = (code) => {
    if (translations[code]) {
      localStorage.setItem('fq_lang', code)
      setLang(code)
    }
  }

  const t = translations[lang]

  return (
    <LangContext.Provider value={{ t, lang, changeLang, LANG_OPTIONS }}>
      {children}
    </LangContext.Provider>
  )
}

export function useLang() {
  return useContext(LangContext)
}

export function LanguageSwitcher({ light = false }) {
  const { lang, changeLang, LANG_OPTIONS: opts } = useLang()
  const [open, setOpen] = useState(false)
  const ref = React.useRef(null)
  const current = opts.find(o => o.code === lang)

  React.useEffect(() => {
    const handler = (e) => {
      if (ref.current && !ref.current.contains(e.target)) setOpen(false)
    }
    document.addEventListener('mousedown', handler)
    return () => document.removeEventListener('mousedown', handler)
  }, [])

  return (
    <div ref={ref} className="relative z-20">
      <button
        onClick={() => setOpen(v => !v)}
        className={`flex items-center gap-1.5 px-2.5 py-1.5 rounded-xl font-bold text-sm transition-all ${light ? 'text-white/80 hover:text-white bg-white/10 hover:bg-white/20' : 'text-gray-500 hover:text-gray-700 bg-gray-100 hover:bg-gray-200'}`}
      >
        <span className="text-base leading-none">{current?.flag}</span>
        <span className="hidden sm:inline text-xs">{current?.code.toUpperCase()}</span>
        <span className="text-xs opacity-60">{open ? '▲' : '▼'}</span>
      </button>
      {open && (
        <div className="absolute right-0 top-full mt-1.5 bg-white rounded-2xl shadow-xl border border-gray-100 overflow-hidden z-50 min-w-[155px]">
          {opts.map(o => (
            <button
              key={o.code}
              onClick={() => { changeLang(o.code); setOpen(false) }}
              className={`w-full flex items-center gap-2.5 px-4 py-2.5 text-sm font-bold transition-colors text-left ${lang === o.code ? 'bg-violet-50 text-violet-700' : 'text-gray-600 hover:bg-gray-50'}`}
            >
              <span className="text-lg">{o.flag}</span>
              <span>{o.label}</span>
              {lang === o.code && <span className="ml-auto text-violet-400 text-xs">✓</span>}
            </button>
          ))}
        </div>
      )}
    </div>
  )
}
